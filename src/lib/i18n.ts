/** Форматирует строку с плейсхолдерами {name}. */
/** Превращает «Command+Alt+KeyZ» в «⌥⌘Z» для отображения. */
export function prettyCombo(combo: string): string {
  if (!combo) return "—";
  return combo
    .split("+")
    .map((part) => {
      switch (part) {
        case "Command":
          return "⌘";
        case "Alt":
          return "⌥";
        case "Control":
          return "⌃";
        case "Shift":
          return "⇧";
        default:
          return part
            .replace(/^Key/, "")
            .replace(/^Digit/, "")
            .replace("Backspace", "⌫")
            .replace("Space", "Space");
      }
    })
    .join(" ");
}
